static int b64dec(const char *s, uint8_t *o) {
    static const char T[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    int n = 0; uint32_t acc = 0; int bits = 0;
    for (; *s && *s != '='; s++) {
        const char *p = strchr(T, *s); if (!p) return -1;
        acc = acc << 6 | (uint32_t)(p - T); bits += 6;
        if (bits >= 8) { bits -= 8; o[n++] = (uint8_t)(acc >> bits); }
    }
    return n;
}
static int parse_guid(const char *s, uint8_t g[8]) {
    int i; if (strlen(s) != 16) return -1;
    for (i = 0; i < 8; i++) { unsigned v; if (sscanf(s + 2 * i, "%2x", &v) != 1) return -1; g[i] = (uint8_t)v; }
    return 0;
}
static uint8_t *rd(const char *dir, const char *name, size_t *n) {
    char p[1024]; FILE *f; long l; uint8_t *b;
    snprintf(p, sizeof p, "%s/%s", dir, name);
    f = fopen(p, "rb"); if (!f) return NULL;
    fseek(f, 0, SEEK_END); l = ftell(f); fseek(f, 0, SEEK_SET);
    b = malloc((size_t)l + 1); if (!b || fread(b, 1, (size_t)l, f) != (size_t)l) { fclose(f); free(b); return NULL; }
    fclose(f); *n = (size_t)l; return b;
}
static int wr(const char *dir, const char *name, const void *d, size_t n) {
    char p[1024]; FILE *f; int ok;
    snprintf(p, sizeof p, "%s/%s", dir, name);
    f = fopen(p, "wb"); if (!f) return -1;
    ok = fwrite(d, 1, n, f) == n; ok &= fclose(f) == 0; return ok ? 0 : -1;
}
static uint32_t rd32(const uint8_t *p) { return p[0] | (uint32_t)p[1] << 8 | (uint32_t)p[2] << 16 | (uint32_t)p[3] << 24; }
static int cmd_make(const char *guid, const char *dir) {
    uint8_t g[8], *lg, *phys, *scr; size_t llen, plen = 0, cap = 1u << 20, ss = 16u << 20, k;
    mdb_sqlgen_out_t so; char itl[1100];
    uint8_t *cbk;
    if (parse_guid(guid, g)) { fprintf(stderr, "bad guid\n"); return 2; }
    lg = malloc(sizeof B64); llen = (size_t)b64dec(B64, lg);
    phys = malloc(cap);
    if (mdb_cdb_pack(lg, llen, phys, cap, &plen, g)) { fprintf(stderr, "pack failed\n"); return 5; }
    scr = malloc(ss);
    for (k = 0; k < 3; k++) { so.cap[k] = 4u << 20; so.buf[k] = malloc(so.cap[k]); so.len[k] = 0; }
    if (mdb_sqlgen_build(lg, llen, &so, scr, ss)) { fprintf(stderr, "sqlgen failed\n"); return 5; }
    cbk = malloc(mdb_cbk_size(so.len[1])); mdb_cbk_build(cbk, so.buf[1], so.len[1], g);
    snprintf(itl, sizeof itl, "%s/iTunes Library.itlp", dir);
    mkdir(dir, 0755); mkdir(itl, 0755);
    if (wr(dir, "iTunesCDB", phys, plen) || wr(itl, "Library.itdb", so.buf[0], so.len[0]) || wr(itl, "Locations.itdb", so.buf[1], so.len[1]) ||
        wr(itl, "Dynamic.itdb", so.buf[2], so.len[2]) || wr(itl, "Locations.itdb.cbk", cbk, mdb_cbk_size(so.len[1]))) { fprintf(stderr, "write failed\n"); return 2; }
    printf("fixture: iTunesCDB %zu B, Library %zu B, Locations %zu B, Dynamic %zu B\n", plen, so.len[0], so.len[1], so.len[2]);
    return 0;
}
static int cmd_verify(const char *guid, const char *dir) {
    uint8_t g[8], *cdb, *loc, *cbk, *lg, *want; size_t ncdb, nloc, ncbk, ll = 0; char itl[1100]; int tracks = -1; uint32_t off;
    if (parse_guid(guid, g)) return 2;
    snprintf(itl, sizeof itl, "%s/iTunes Library.itlp", dir);
    cdb = rd(dir, "iTunesCDB", &ncdb); loc = rd(itl, "Locations.itdb", &nloc); cbk = rd(itl, "Locations.itdb.cbk", &ncbk);
    if (!cdb || !loc || !cbk) { printf("MISSING files\n"); return 3; }
    if (!mdb_cdb_verify(cdb, ncdb, g)) { printf("HASHAB INVALID\n"); return 3; }
    want = malloc(mdb_cbk_size(nloc)); mdb_cbk_build(want, loc, nloc, g);
    if (ncbk != mdb_cbk_size(nloc) || memcmp(want, cbk, ncbk)) { printf("CBK INVALID\n"); return 3; }
    lg = malloc(ncdb * 16 + 65536);
    if (mdb_cdb_unpack(cdb, ncdb, lg, ncdb * 16 + 65536, &ll)) { printf("UNPACK FAILED\n"); return 3; }
    off = rd32(lg + 4);
    while (off + 16 <= ll && !memcmp(lg + off, "mhsd", 4)) {
        uint32_t hl = rd32(lg + off + 4), tl = rd32(lg + off + 8);
        if (rd32(lg + off + 12) == 1) { tracks = (int)rd32(lg + off + hl + 8); break; }
        off += tl;
    }
    printf("HASHAB OK\nCBK OK\nTRACKS %d\n", tracks);
    return 0;
}
int main(int argc, char **argv) {
    if (argc == 4 && !strcmp(argv[1], "make")) return cmd_make(argv[2], argv[3]);
    if (argc == 4 && !strcmp(argv[1], "verify")) return cmd_verify(argv[2], argv[3]);
    fprintf(stderr, "usage: nsfix make|verify <guid16> <itunes_dir>\n");
    return 2;
}
